package main

import (
	"context"
	"flag"
	"fmt"
	"io"
	"os"
	"os/signal"
	"strings"
	"syscall"
	"time"

	pmtools "github.com/polymetrics-ai/pm-cli/tools"
)

const generationTimeout = 5 * time.Minute

func main() {
	os.Exit(run(os.Args[1:], os.Stderr))
}

func run(arguments []string, stderr io.Writer) int {
	flags := flag.NewFlagSet("pm-api-generate", flag.ContinueOnError)
	flags.SetOutput(stderr)
	flags.Usage = func() {
		fmt.Fprintln(stderr, "Usage: pm-api-generate --root ROOT [--output-root ROOT] [--spec FILE] [--admin-spec FILE] [--controls FILE] [--config FILE] [--check]")
		fmt.Fprintln(stderr, "Validate the accepted OpenAPI/control sources and deterministically generate or compare every owned API projection.")
		flags.PrintDefaults()
	}
	root := flags.String("root", "", "repository root containing the accepted API sources")
	outputRoot := flags.String("output-root", "", "output tree; defaults to --root")
	spec := flags.String("spec", "", "OpenAPI source; defaults to api/pm.openapi.yaml under --root")
	adminSpec := flags.String("admin-spec", "", "private API source; defaults to api/admin.openapi.yaml under --root")
	controls := flags.String("controls", "", "control source; defaults to api/controls.json under --root")
	configuration := flags.String("config", "", "oapi-codegen configuration; defaults to api/oapi-codegen.yaml under --root")
	check := flags.Bool("check", false, "compare exact generated bytes without writing")
	if err := flags.Parse(arguments); err != nil {
		return 2
	}
	if flags.NArg() != 0 {
		fmt.Fprintf(stderr, "pm-api-generate: unexpected positional arguments: %s\n", strings.Join(flags.Args(), " "))
		return 2
	}
	if strings.TrimSpace(*root) == "" {
		fmt.Fprintln(stderr, "pm-api-generate: --root is required")
		flags.Usage()
		return 2
	}
	if *outputRoot == "" {
		*outputRoot = *root
	}

	signalContext, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stop()
	ctx, cancel := context.WithTimeout(signalContext, generationTimeout)
	defer cancel()
	if err := pmtools.GenerateAPI(ctx, pmtools.APIGenerationOptions{
		Root:          *root,
		OutputRoot:    *outputRoot,
		SpecPath:      *spec,
		ControlsPath:  *controls,
		AdminSpecPath: *adminSpec,
		ConfigPath:    *configuration,
		Check:         *check,
	}); err != nil {
		fmt.Fprintf(stderr, "pm-api-generate: %v\n", err)
		return 1
	}
	return 0
}
