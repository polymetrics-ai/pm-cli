func mutateFixtureJSON(t *testing.T, path string, mutate func(map[string]any)) {
	t.Helper()
	var document map[string]any
	readFixtureJSON(t, path, &document)
	mutate(document)
	writeFixtureJSON(t, path, document)
}

func foundationAt(document map[string]any, field string, index int) map[string]any {
	return document[field].([]any)[index].(map[string]any)
}

func readFixtureJSON(t *testing.T, path string, destination any) {
	t.Helper()
	contents, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if err := json.Unmarshal(contents, destination); err != nil {
		t.Fatal(err)
	}
}

func writeFixtureJSON(t *testing.T, path string, document any) {
	t.Helper()
	encoded, err := json.MarshalIndent(document, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	writeFixtureFile(t, path, append(encoded, '\n'))
}

func writeFixtureFile(t *testing.T, path string, contents []byte) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, contents, 0o644); err != nil {
		t.Fatal(err)
	}
}

