var atlasRunfile string

func TestTraceabilityClosure(t *testing.T) {
	binary := buildAtlasCommand(t)

	t.Run("complete declared map remains authoring-only", func(t *testing.T) {
		root := writeCompleteTraceabilityFixture(t)
		output, err := runAtlasCommand(binary, root, 1, false)
		if err != nil {
			t.Fatalf("generate complete synthetic atlas: %v\n%s", err, output)
		}

		var atlas struct {
			Authority   string `json:"authority"`
			Foundations []struct {
				ID                   string `json:"id"`
				ImplementationState  string `json:"implementation_state"`
				EvidenceState        string `json:"evidence_state"`
				CapabilityState      string `json:"capability_state"`
				RegistrationBindings []struct {
					Path             string `json:"path"`
					Symbol           string `json:"symbol"`
					DeclarationState string `json:"declaration_state"`
				} `json:"registration_bindings"`
			} `json:"foundations"`
		}
		readFixtureJSON(t, filepath.Join(root, "docs/foundations/atlas.json"), &atlas)
		if !strings.Contains(atlas.Authority, "authoring_projection_only") {
			t.Fatalf("atlas authority = %q; want authoring-only projection", atlas.Authority)
		}
		if len(atlas.Foundations) != 1 {
			t.Fatalf("atlas foundation count = %d; want 1", len(atlas.Foundations))
		}
		foundation := atlas.Foundations[0]
		if foundation.ID != "FND-01" || foundation.ImplementationState != "implemented" || foundation.EvidenceState != "unexecuted" || foundation.CapabilityState != "not_established_by_atlas" {
			t.Fatalf("foundation state = %#v; implementation, evidence and capability must remain distinct", foundation)
		}
		if len(foundation.RegistrationBindings) != 1 || foundation.RegistrationBindings[0].Path != "internal/compile/source.go" || foundation.RegistrationBindings[0].Symbol != "CaptureSource" || foundation.RegistrationBindings[0].DeclarationState != "present" {
			t.Fatalf("registration binding = %#v; want observed CaptureSource declaration", foundation.RegistrationBindings)
		}

		var requirements struct {
			Authority    string `json:"authority"`
			Requirements []struct {
				ID             string `json:"id"`
				DeclaredStatus string `json:"declared_status"`
			} `json:"requirements"`
		}
		readFixtureJSON(t, filepath.Join(root, "docs/foundations/requirements.json"), &requirements)
		if !strings.Contains(requirements.Authority, "design_impact_projection_only") || len(requirements.Requirements) != 1 || requirements.Requirements[0].ID != "REQ-SYNTHETIC" || requirements.Requirements[0].DeclaredStatus != "planned" {
			t.Fatalf("requirements projection invented readiness: %#v", requirements)
		}
		output, err = runAtlasCommand(binary, root, 1, true)
		if err != nil {
			t.Fatalf("check exact generated bytes: %v\n%s", err, output)
		}
	})

	t.Run("missing CaptureSource consumer", func(t *testing.T) {
		root := writeCompleteTraceabilityFixture(t)
		mutateFixtureJSON(t, foundationsFixturePath(root), func(document map[string]any) {
			foundationAt(document, "foundations", 0)["consumers"] = []any{}
		})
		requireAtlasFailure(t, binary, root, 1, "missing-consumer closure", "/foundations/0/consumers", "FND-01")
	})

	t.Run("wrong FND-01 version", func(t *testing.T) {
		root := writeCompleteTraceabilityFixture(t)
		mutateFixtureJSON(t, mappingsFixturePath(root), func(document map[string]any) {
			requirement := foundationAt(document, "requirements", 0)
			refs := requirement["foundation_refs"].([]any)
			refs[0].(map[string]any)["version"] = "9.9.9"
		})
		requireAtlasFailure(t, binary, root, 1, "unresolved contract version", "/requirements/0/foundation_refs/0", "FND-01@9.9.9")
	})

	t.Run("ownerless Go file", func(t *testing.T) {
		root := writeCompleteTraceabilityFixture(t)
		writeFixtureFile(t, filepath.Join(root, "internal/fixture/orphan.go"), []byte("package fixture\n"))
		requireAtlasFailure(t, binary, root, 1, "ownerless file", "internal~1fixture~1orphan.go")
	})

	t.Run("missing declared handler", func(t *testing.T) {
		root := writeCompleteTraceabilityFixture(t)
		writeFixtureFile(t, filepath.Join(root, "internal/compile/source.go"), []byte("package compile\n\nfunc DifferentConsumer() {}\n"))
		requireAtlasFailure(t, binary, root, 1, "missing-handler closure", "/foundations/0/registration_point", "CaptureSource")
	})

	t.Run("stale generated bytes", func(t *testing.T) {
		root := writeCompleteTraceabilityFixture(t)
		output, err := runAtlasCommand(binary, root, 1, false)
		if err != nil {
			t.Fatalf("prepare exact generated bytes: %v\n%s", err, output)
		}
		atlasPath := filepath.Join(root, "docs/foundations/atlas.json")
		contents, err := os.ReadFile(atlasPath)
		if err != nil {
			t.Fatal(err)
		}
		contents = append(contents, []byte(" \n")...)
		if err := os.WriteFile(atlasPath, contents, 0o644); err != nil {
			t.Fatal(err)
		}
		output, err = runAtlasCommand(binary, root, 1, true)
		if err == nil || !strings.Contains(output, "stale generated artifact") || !strings.Contains(output, "docs~1foundations~1atlas.json") {
			t.Fatalf("stale parity result = %v\n%s", err, output)
		}
	})

	t.Run("duplicate semantic authority", func(t *testing.T) {
		root := writeCompleteTraceabilityFixture(t)
		mutateFixtureJSON(t, foundationsFixturePath(root), func(document map[string]any) {
			foundations := document["foundations"].([]any)
			encoded, err := json.Marshal(foundations[0])
			if err != nil {
				t.Fatal(err)
			}
			var duplicate map[string]any
			if err := json.Unmarshal(encoded, &duplicate); err != nil {
				t.Fatal(err)
			}
			duplicate["id"] = "FND-02"
			duplicate["name"] = "Competing source capture"
			document["foundations"] = append(foundations, duplicate)
		})
		requireAtlasFailure(t, binary, root, 2, "duplicate authority", "/foundations/1/interface", "FND-01")
	})

	t.Run("pass without exact receipt", func(t *testing.T) {
		root := writeCompleteTraceabilityFixture(t)
		mutateFixtureJSON(t, validationFixturePath(root), func(document map[string]any) {
			foundationAt(document, "entries", 0)["command_status"] = "PASS"
		})
		requireAtlasFailure(t, binary, root, 1, "unsupported evidence claim", "/validations/V80/receipt", "exact matching receipt")
	})
}

func buildAtlasCommand(t *testing.T) string {
	t.Helper()
	runfilesRoot := os.Getenv("TEST_SRCDIR")
	if runfilesRoot != "" {
		if atlasRunfile == "" {
			t.Fatal("declared Atlas runfile identity is unavailable")
		}
		if !filepath.IsAbs(runfilesRoot) {
			t.Fatal("Bazel runfiles root must be absolute")
		}
		relative := filepath.FromSlash(atlasRunfile)
		if !filepath.IsLocal(relative) {
			t.Fatalf("Atlas runfile path is not local: %q", atlasRunfile)
		}
		binary := filepath.Join(filepath.Clean(runfilesRoot), relative)
		information, err := os.Stat(binary)
		if err != nil {
			t.Fatalf("locate declared Atlas runfile: %v", err)
		}
		if !information.Mode().IsRegular() {
			t.Fatal("declared Atlas runfile is not a regular file")
		}
		return binary
	}
	if atlasRunfile != "" {
		t.Fatal("declared Atlas runfile has no Bazel runfiles root")
	}

	toolsRoot, err := os.Getwd()
	if err != nil {
		t.Fatalf("resolve tools source directory: %v", err)
	}
	for _, relative := range []string{"go.mod", "atlas/main.go"} {
		information, statErr := os.Stat(filepath.Join(toolsRoot, relative))
		if statErr != nil || !information.Mode().IsRegular() {
			t.Fatalf("ordinary tools test is not running from the declared tools module: %s", relative)
		}
	}
	binary := filepath.Join(t.TempDir(), "pm-foundation-atlas")
	goCommand := os.Getenv("PM_GO")
	if goCommand == "" {
		goCommand = "go"
	}
	command := exec.Command(goCommand, "build", "-mod=readonly", "-o", binary, "./atlas")
	command.Dir = toolsRoot
	command.Env = append(os.Environ(), "GOWORK=off")
	output, err := command.CombinedOutput()
	if err != nil {
		t.Fatalf("build Atlas command: %v\n%s", err, output)
	}
	return binary
}

func runAtlasCommand(binary, root string, expectedFoundations int, check bool) (string, error) {
	arguments := []string{
		"--root", root,
		"--expected-foundations", jsonNumber(expectedFoundations),
		"--expected-requirements", "1",
		"--expected-packets", "1",
	}
	if check {
		arguments = append(arguments, "--check")
	}
	command := exec.Command(binary, arguments...)
	output, err := command.CombinedOutput()
	return string(output), err
}

func requireAtlasFailure(t *testing.T, binary, root string, expectedFoundations int, fragments ...string) {
	t.Helper()
	output, err := runAtlasCommand(binary, root, expectedFoundations, false)
	if err == nil {
		t.Fatalf("Atlas accepted causal fault; output:\n%s", output)
	}
	for _, fragment := range fragments {
		if !strings.Contains(output, fragment) {
			t.Fatalf("Atlas fault diagnostic omitted %q: %v\n%s", fragment, err, output)
		}
	}
}

